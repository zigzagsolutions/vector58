import { z } from 'zod';
import {
  BrowserSchema,
  IndicatorTypeSchema,
  IsoDateTimeSchema,
  SeveritySchema,
  SlugSchema,
  ThreatCategorySchema,
  UuidSchema,
} from './common';
import {
  BrowserClientSchema,
  EndpointCommandStatusSchema,
  EndpointCommandTypeSchema,
  PolicyRuleTypeSchema,
  SecurityEventTypeSchema,
} from './entities';
import { PolicyPayloadSchema } from './policy-payload';

/* ---------- Device API (agent -> cloud) ---------- */

const shortText = (max: number) => z.string().trim().min(1).max(max);

export const EnrollmentRequestSchema = z.object({
  enrollmentToken: z.string().min(16).max(256),
  /** Stable per-install identifier generated by the agent; not trusted for tenancy. */
  installationId: UuidSchema,
  hostname: shortText(255),
  osVersion: shortText(255),
  agentVersion: shortText(32),
  localIp: z.string().max(64).nullable().optional(),
  machine: z
    .object({
      manufacturer: z.string().max(128).optional(),
      model: z.string().max(128).optional(),
      domain: z.string().max(255).optional(),
      osBuild: z.string().max(64).optional(),
    })
    .optional(),
  /** Reserved for keypair device authentication (Phase 2). */
  publicKey: z.string().max(4096).optional(),
});
export type EnrollmentRequest = z.infer<typeof EnrollmentRequestSchema>;

export const EnrollmentResponseSchema = z.object({
  deviceId: UuidSchema,
  organizationId: UuidSchema,
  organizationName: z.string(),
  /** Bearer secret returned exactly once; the agent stores it with DPAPI. */
  deviceSecret: z.string(),
  heartbeatIntervalSeconds: z.number().int().positive(),
  policyPollIntervalSeconds: z.number().int().positive(),
  enrolledAt: IsoDateTimeSchema,
});
export type EnrollmentResponse = z.infer<typeof EnrollmentResponseSchema>;

export const ReportedBrowserClientSchema = BrowserClientSchema.omit({ lastSeenAt: true });
export type ReportedBrowserClient = z.infer<typeof ReportedBrowserClientSchema>;

export const AgentHeartbeatSchema = z.object({
  hostname: shortText(255),
  osVersion: shortText(255),
  agentVersion: shortText(32),
  localIp: z.string().max(64).nullable().optional(),
  policyVersion: z.number().int().nonnegative().nullable(),
  policyChecksum: z.string().max(64).nullable().optional(),
  uptimeSeconds: z.number().int().nonnegative().optional(),
  browserClients: z.array(ReportedBrowserClientSchema).max(16).default([]),
});
export type AgentHeartbeat = z.infer<typeof AgentHeartbeatSchema>;

export const HeartbeatResponseSchema = z.object({
  serverTime: IsoDateTimeSchema,
  latestPolicyVersion: z.number().int().nullable(),
  pendingCommands: z.number().int().nonnegative(),
});
export type HeartbeatResponse = z.infer<typeof HeartbeatResponseSchema>;

export const DevicePolicyResponseSchema = z.discriminatedUnion('status', [
  z.object({ status: z.literal('current'), policyVersion: z.number().int().nullable() }),
  z.object({
    status: z.literal('updated'),
    policyVersion: z.number().int(),
    payload: PolicyPayloadSchema,
  }),
  z.object({ status: z.literal('none') }),
]);
export type DevicePolicyResponse = z.infer<typeof DevicePolicyResponseSchema>;

export const DeviceCommandSchema = z.object({
  id: UuidSchema,
  commandType: EndpointCommandTypeSchema,
  payload: z.record(z.string(), z.unknown()),
  issuedAt: IsoDateTimeSchema,
  expiresAt: IsoDateTimeSchema,
});
export type DeviceCommand = z.infer<typeof DeviceCommandSchema>;

export const CommandResultRequestSchema = z.object({
  status: EndpointCommandStatusSchema.extract(['RUNNING', 'COMPLETED', 'FAILED']),
  result: z.record(z.string(), z.unknown()).optional(),
  error: z.string().max(2000).optional(),
});
export type CommandResultRequest = z.infer<typeof CommandResultRequestSchema>;

/** Event as reported by an endpoint. Tenant and device come from authentication, never the body. */
export const ReportedSecurityEventSchema = z.object({
  eventId: UuidSchema,
  eventType: SecurityEventTypeSchema,
  occurredAt: IsoDateTimeSchema,
  browserClientId: z.string().max(64).nullable().optional(),
  browser: BrowserSchema.nullable().optional(),
  browserVersion: z.string().max(64).nullable().optional(),
  extensionVersion: z.string().max(32).nullable().optional(),
  url: z.string().max(2048).nullable().optional(),
  domain: z.string().max(253).nullable().optional(),
  ruleId: z.number().int().positive().nullable().optional(),
  policyVersion: z.number().int().nonnegative().nullable().optional(),
  threatCategory: ThreatCategorySchema.nullable().optional(),
  details: z.record(z.string(), z.unknown()).optional(),
});
export type ReportedSecurityEvent = z.infer<typeof ReportedSecurityEventSchema>;

export const SecurityEventBatchSchema = z.object({
  events: z.array(ReportedSecurityEventSchema).min(1).max(500),
});
export type SecurityEventBatch = z.infer<typeof SecurityEventBatchSchema>;

/* ---------- Management API (portal -> cloud) ---------- */

export const CreateOrganizationRequestSchema = z.object({
  name: z.string().trim().min(2).max(120),
  slug: SlugSchema,
});
export type CreateOrganizationRequest = z.infer<typeof CreateOrganizationRequestSchema>;

export const CreatePolicyRequestSchema = z.object({
  name: z.string().trim().min(1).max(120),
  description: z.string().trim().max(500).optional(),
  includeGlobalThreats: z.boolean().default(true),
});
export type CreatePolicyRequest = z.infer<typeof CreatePolicyRequestSchema>;

export const CreateRuleRequestSchema = z.object({
  policyId: UuidSchema.optional(),
  ruleType: PolicyRuleTypeSchema,
  value: z.string().trim().min(1).max(2048),
  category: ThreatCategorySchema.default('custom'),
  priority: z.number().int().min(0).max(1000).default(100),
  reason: z.string().trim().max(500).optional(),
  expiresAt: IsoDateTimeSchema.optional(),
});
export type CreateRuleRequest = z.infer<typeof CreateRuleRequestSchema>;

export const AddTenantUserRequestSchema = z.object({
  email: z.email().transform((e) => e.toLowerCase()),
  roleKey: z.string().min(1).max(64),
});
export type AddTenantUserRequest = z.infer<typeof AddTenantUserRequestSchema>;

export const CreateIndicatorRequestSchema = z.object({
  indicatorType: IndicatorTypeSchema,
  value: z.string().trim().min(1).max(2048),
  threatCategory: ThreatCategorySchema,
  confidence: z.number().int().min(0).max(100).default(90),
  severity: SeveritySchema.default('high'),
  expiresAt: IsoDateTimeSchema.optional(),
});
export type CreateIndicatorRequest = z.infer<typeof CreateIndicatorRequestSchema>;

export const CreateIncidentRequestSchema = z.object({
  title: z.string().trim().min(3).max(200),
  description: z.string().trim().max(5000).optional(),
  severity: SeveritySchema.default('medium'),
});

export const CreateCommandRequestSchema = z.object({
  deviceId: UuidSchema,
  commandType: EndpointCommandTypeSchema,
  incidentId: UuidSchema.optional(),
  payload: z.record(z.string(), z.unknown()).default({}),
});

export const CreateEnrollmentTokenRequestSchema = z.object({
  description: z.string().trim().max(200).optional(),
  maxUses: z.number().int().min(1).max(100_000).default(25),
  expiresInHours: z
    .number()
    .int()
    .min(1)
    .max(24 * 90)
    .default(72),
});

/** Standard API envelope for errors. */
export const ApiErrorSchema = z.object({
  error: z.object({
    code: z.string(),
    message: z.string(),
    details: z.unknown().optional(),
  }),
  apiVersion: z.literal('v1'),
});
export type ApiError = z.infer<typeof ApiErrorSchema>;
