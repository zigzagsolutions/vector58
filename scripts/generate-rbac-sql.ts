/**
 * Generates supabase/migrations/20261028000009_rbac_reference_data.sql from
 * @bsp/auth-permissions so the TypeScript catalog and the database never drift.
 *
 *   pnpm tsx scripts/generate-rbac-sql.ts > supabase/migrations/20261028000009_rbac_reference_data.sql
 *
 * tests/tenant-isolation/rbac-sync.test.ts fails if the migration is stale.
 * NOTE: once a migration has been applied to production it must not be edited;
 * catalog changes after go-live are emitted as a new migration with --since.
 */
import {
  ALL_PERMISSIONS,
  ALL_ROLES,
  PERMISSION_DESCRIPTIONS,
  permissionScope,
} from '../packages/auth-permissions/src/index';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function generateRbacSql(): string {
  const lines: string[] = [];
  lines.push('-- =============================================================================');
  lines.push('-- RBAC reference data. GENERATED by scripts/generate-rbac-sql.ts - do not edit.');
  lines.push('-- Source of truth: packages/auth-permissions.');
  lines.push('-- =============================================================================');
  lines.push('');
  lines.push('insert into public.permissions (key, scope, description) values');
  lines.push(
    ALL_PERMISSIONS.map(
      (p) => `  (${q(p)}, ${q(permissionScope(p))}, ${q(PERMISSION_DESCRIPTIONS[p])})`,
    ).join(',\n') +
      '\non conflict (key) do update set scope = excluded.scope, description = excluded.description;',
  );
  lines.push('');
  lines.push('insert into public.roles (key, scope, name, description, is_system) values');
  lines.push(
    ALL_ROLES.map(
      (r) => `  (${q(r.key)}, ${q(r.scope)}, ${q(r.name)}, ${q(r.description)}, true)`,
    ).join(',\n') +
      '\non conflict (key, organization_id) do update set name = excluded.name, description = excluded.description;',
  );
  lines.push('');
  lines.push('insert into public.role_permissions (role_id, permission_key)');
  lines.push('select r.id, v.permission_key from (values');
  const pairs: string[] = [];
  for (const r of ALL_ROLES) {
    const perms =
      r.scope === 'platform'
        ? [...r.permissions, ...r.tenantContextPermissions]
        : [...r.permissions];
    for (const p of perms) pairs.push(`  (${q(r.key)}, ${q(p)})`);
  }
  lines.push(pairs.join(',\n'));
  lines.push(') as v(role_key, permission_key)');
  lines.push('join public.roles r on r.key = v.role_key and r.organization_id is null');
  lines.push('on conflict do nothing;');
  lines.push('');
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('generate-rbac-sql.ts')) {
  process.stdout.write(generateRbacSql());
}
